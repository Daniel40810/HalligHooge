-- HalligHooge · Messarchiv (DB1, Werkbuch HalligHooge 167): Sichten.
-- Sturmflut nach BSH (Nordsee): Hochwasser 1,5 bis 2,5 m über dem mittleren Hochwasser (MThw), schwere ab 2,5 m,
-- sehr schwere ab 3,5 m. Zusammenhängende Tiden (Abstand unter 18 h) sind ein Ereignis (MATCH_RECOGNIZE).
-- Landunter am Ort: geschätztes Hochwasser über der Schwelle NASS (HH_SCHWELLE).

CREATE OR REPLACE VIEW HH_STATION_V AS
SELECT s.STATION_ID, s.ART, s.SCHLUESSEL, s.NAME, s.KENNUNG, s.GEWAESSER, s.HOEHE, s.MTHW, s.AKTIV, s.LAGE,
       MDSYS.SDO_CS.TRANSFORM(s.LAGE, 8307) AS LAGE_WGS84,
       (SELECT MAX(r.ZEIT) FROM HH_ROH r WHERE r.STATION_ID = s.STATION_ID AND r.GROESSE = 'W') AS LETZTER_ROHWERT,
       (SELECT MAX(m.ZEIT) FROM HH_MITTEL m WHERE m.STATION_ID = s.STATION_ID AND m.GROESSE = CASE s.ART WHEN 'WIND' THEN 'FF' ELSE 'W' END) AS LETZTES_MITTEL
FROM HH_STATION s;

CREATE OR REPLACE VIEW HH_FUELLSTAND_V AS
SELECT NVL(i.TABLE_NAME, s.SEGMENT_NAME) AS TABELLE, ROUND(SUM(s.BYTES) / 1048576, 1) AS MB, COUNT(*) AS SEGMENTE
FROM USER_SEGMENTS s LEFT JOIN USER_INDEXES i ON i.INDEX_NAME = s.SEGMENT_NAME
GROUP BY NVL(i.TABLE_NAME, s.SEGMENT_NAME);

CREATE OR REPLACE VIEW HH_HOCHWASSER_V AS
SELECT h.STATION_ID, s.SCHLUESSEL, s.NAME, h.ZEIT, h.HOEHE, h.GEZEIT, h.STAU, h.HOEHE - s.MTHW AS UEBER_MTHW, h.HERKUNFT,
       CASE WHEN h.HOEHE - s.MTHW >= 3.5 THEN 'sehr schwere Sturmflut'
            WHEN h.HOEHE - s.MTHW >= 2.5 THEN 'schwere Sturmflut'
            WHEN h.HOEHE - s.MTHW >= 1.5 THEN 'Sturmflut' END AS KLASSE
FROM HH_SCHEITEL h JOIN HH_STATION s ON s.STATION_ID = h.STATION_ID
WHERE h.ART = 'H';

CREATE OR REPLACE VIEW HH_STURMFLUT_V AS
SELECT m.STATION_ID, s.SCHLUESSEL, s.NAME, m.AB, m.BIS, m.TIDEN, m.SCHEITEL, m.UEBER AS UEBER_MTHW, m.STAU_MAX,
       CASE WHEN m.UEBER >= 3.5 THEN 'sehr schwere Sturmflut' WHEN m.UEBER >= 2.5 THEN 'schwere Sturmflut' ELSE 'Sturmflut' END AS KLASSE
FROM (SELECT STATION_ID, ZEIT, HOEHE, STAU, UEBER_MTHW FROM HH_HOCHWASSER_V WHERE UEBER_MTHW IS NOT NULL)
MATCH_RECOGNIZE (
  PARTITION BY STATION_ID
  ORDER BY ZEIT
  MEASURES FIRST(ZEIT) AS AB, LAST(ZEIT) AS BIS, COUNT(*) AS TIDEN, MAX(HOEHE) AS SCHEITEL, MAX(UEBER_MTHW) AS UEBER, MAX(STAU) AS STAU_MAX
  ONE ROW PER MATCH
  AFTER MATCH SKIP PAST LAST ROW
  PATTERN (A B*)
  DEFINE A AS A.UEBER_MTHW >= 1.5,
         B AS B.UEBER_MTHW >= 1.5 AND B.ZEIT - PREV(B.ZEIT) < 0.75
) m JOIN HH_STATION s ON s.STATION_ID = m.STATION_ID;

CREATE OR REPLACE VIEW HH_SCHAETZUNG_V AS
SELECT h.STATION_ID, s.SCHLUESSEL, s.NAME, h.ZEIT, h.HOEHE, h.GEZEIT, h.STAU, k.HOEHE AS KRONE, n.HOEHE AS NASS,
       CASE WHEN h.HOEHE >= n.HOEHE THEN 'Landunter' WHEN h.HOEHE >= k.HOEHE THEN 'über der Krone' END AS BEFUND
FROM HH_SCHEITEL h JOIN HH_STATION s ON s.STATION_ID = h.STATION_ID
LEFT JOIN HH_SCHWELLE k ON k.STATION_ID = h.STATION_ID AND k.ART = 'KRONE'
LEFT JOIN HH_SCHWELLE n ON n.STATION_ID = h.STATION_ID AND n.ART = 'NASS'
WHERE h.ART = 'H' AND h.HERKUNFT = 'SCHAETZUNG';

CREATE OR REPLACE VIEW HH_LANDUNTER_V AS
SELECT m.STATION_ID, s.SCHLUESSEL, m.AB, m.BIS, m.TIDEN, m.SCHEITEL, m.STAU_MAX
FROM (SELECT STATION_ID, ZEIT, HOEHE, STAU, NASS FROM HH_SCHAETZUNG_V WHERE NASS IS NOT NULL)
MATCH_RECOGNIZE (
  PARTITION BY STATION_ID
  ORDER BY ZEIT
  MEASURES FIRST(ZEIT) AS AB, LAST(ZEIT) AS BIS, COUNT(*) AS TIDEN, MAX(HOEHE) AS SCHEITEL, MAX(STAU) AS STAU_MAX
  ONE ROW PER MATCH
  AFTER MATCH SKIP PAST LAST ROW
  PATTERN (A B*)
  DEFINE A AS A.HOEHE >= A.NASS,
         B AS B.HOEHE >= B.NASS AND B.ZEIT - PREV(B.ZEIT) < 0.75
) m JOIN HH_STATION s ON s.STATION_ID = m.STATION_ID;
