-- HalligHooge · Messarchiv (DB1, Werkbuch HalligHooge 167; F261–F265 A)
-- Schema HALLIGHOOGE, Präfix HH_, Lage in ETRS89 / UTM 32 (SRID 25832), Zeiten in UTC.
-- Ausgeführt von com.dan.store.Einrichter (über com.dan.steuerhaus.messung.Sammler --einrichten); er löscht nie etwas.
-- Lesbar in SQL Developer. Regeln für den Einrichter: je Spalte eine Zeile, keine Kommentare in den Zeilen einer Tabelle,
-- alles nach den Spalten (Platz, Fächer) in der Zeile, die mit ")" beginnt.
--
-- Wachstumsgrenze: Nur der Sammler fügt Werte ein, und er räumt bei jedem Lauf selbst auf (Aufbewahrung.java).
-- HH_ROH liegt in Monatsfächern, HH_MITTEL in Jahresfächern (Partitionen nach Intervall); ein Fach fällt als Ganzes weg
-- (ALTER TABLE … DROP PARTITION), ohne Trigger und ohne einzelne Zeilen zu löschen. Das erste Fach (vor 2000) ist der
-- Anker der Intervalle und bleibt leer.

